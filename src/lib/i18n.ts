export const dictionaries = { en, hi };

export function parseLang(value?: string | null): Lang {
  return value === "hi" ? "hi" : "en";
}

type Dict = typeof en;

export function translate(lang: Lang, key: string): string {
  const parts = key.split(".");
  let current: unknown = dictionaries[lang];
  for (const part of parts) {
    if (typeof current !== "object" || current === null || !(part in current)) {
      current = undefined;
      break;
    }
    current = (current as Record<string, unknown>)[part];
  }
  if (typeof current === "string") return current;

  let fallback: unknown = dictionaries.en;
  for (const part of parts) {
    if (typeof fallback !== "object" || fallback === null || !(part in fallback)) {
      return key;
    }
    fallback = (fallback as Record<string, unknown>)[part];
  }
  return typeof fallback === "string" ? fallback : key;
}

